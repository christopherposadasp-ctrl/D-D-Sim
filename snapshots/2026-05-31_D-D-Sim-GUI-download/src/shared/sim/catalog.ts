import type { Footprint, GridPosition, TerrainFeature } from './types';
import {
  GRID_SIZE,
  HORIZONTAL_2_FOOTPRINT,
  SINGLE_SQUARE_FOOTPRINT,
} from './spatial';

const TERRAIN_COORDINATES_ARE_TOP_LEFT_ORIGIN = false;

function terrainPosition(x: number, y: number): GridPosition {
  return {
    x,
    y: TERRAIN_COORDINATES_ARE_TOP_LEFT_ORIGIN ? GRID_SIZE + 1 - y : y,
  };
}

function terrain(
  featureId: string,
  kind: TerrainFeature['kind'],
  x: number,
  y: number,
  footprint: Footprint = SINGLE_SQUARE_FOOTPRINT,
): TerrainFeature {
  return {
    featureId,
    kind,
    position: terrainPosition(x, y),
    footprint,
  };
}

function cloneFootprint(footprint: Footprint): Footprint {
  return Array.isArray(footprint)
    ? footprint.map((offset) => ({ ...offset }))
    : { ...footprint };
}

function cloneTerrainFeature(feature: TerrainFeature): TerrainFeature {
  return {
    ...feature,
    position: { ...feature.position },
    footprint: cloneFootprint(feature.footprint),
  };
}

